// Keep the lobby's model, equipment and loadout code identical to battle preparation.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),html=fs.readFileSync(root+'/savas.html','utf8');
const from=html.indexOf('var ARENA_ASSET_BASE='),to=html.indexOf('var LudusItemSystem =',from);
if(from<0||to<from)throw Error('Shared gladiator runtime markers changed');
const source='/* Generated by scripts/build-ranked-runtime-v253.cjs from savas.html. */\n'+html.slice(from,to).replace(/[ \t]+$/gm,'').trimEnd()+'\n';
const destination=root+'/ranked-gladiator-runtime-v253.js';
if(process.argv.includes('--check')){
 if(fs.readFileSync(destination,'utf8')!==source)throw Error('Ranked model runtime differs from battle preparation');
}else fs.writeFileSync(destination,source);
